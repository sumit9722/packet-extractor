"""Write preprocess_params.hpp from ../assets/preprocessing.json and model_parameters.h.

Run from anywhere:  python3 pynq-pl/hls/gen_params.py

The constants are written with repr(), which gives the shortest decimal that
reads back as exactly the same double, so the C++ compiler sees the same
values that NumPy uses in svdd_ps/preprocess.py.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASSETS = HERE.parent / "assets"
FEATURES = ("IN_BYTES", "OUT_BYTES", "FLOW_DURATION_MILLISECONDS", "MIN_TTL",
            "MAX_IP_PKT_LEN", "MIN_IP_PKT_LEN", "TCP_WIN_MAX_IN", "TCP_WIN_MAX_OUT")


def main():
    contract = json.loads((ASSETS / "preprocessing.json").read_text())
    entries = contract["entries"]
    assert tuple(e["raw_column"] for e in entries) == FEATURES, "feature order changed"
    assert all(float(e["median"]).is_integer() for e in entries), "medians must be whole numbers"
    header = (ASSETS / "model_parameters.h").read_text()
    thr = dict(re.findall(r"\b(THRESHOLD|VALIDATION_THRESHOLD)\s*=\s*(\d+)", header))

    def arr(name, ctype, values):
        return f"static const {ctype} {name}[8] = {{{', '.join(values)}}};"

    lines = [
        "#pragma once",
        "// Generated by gen_params.py from assets/preprocessing.json and assets/model_parameters.h.",
        "// Feature order: " + ", ".join(FEATURES),
        "// x = MEDIAN if unknown (or MIN_TTL > 255); out = float32((clip(log1p?(x), CLIP_LO, CLIP_HI) - ANCHOR) / SCALE), in double",
        "namespace svpl {",
        arr("PRE_LOG1P", "bool", ["true" if e["log1p"] else "false" for e in entries]),
        arr("PRE_MEDIAN", "unsigned", [str(int(e["median"])) for e in entries]),
        arr("PRE_CLIP_LO", "double", [repr(float(e["clip_lower"])) for e in entries]),
        arr("PRE_CLIP_HI", "double", [repr(float(e["clip_upper"])) for e in entries]),
        arr("PRE_ANCHOR", "double", [repr(float(e["anchor_lower"])) for e in entries]),
        arr("PRE_SCALE", "double", [repr(float(e["scale"])) for e in entries]),
        f"static const unsigned long long SCORE_THRESHOLD = {thr['THRESHOLD']}ULL;",
        f"static const unsigned long long SCORE_THRESHOLD_RECAL = {thr['VALIDATION_THRESHOLD']}ULL;",
        "}  // namespace svpl",
        "",
    ]
    out = HERE / "preprocess_params.hpp"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")
    write_cordic()


def write_cordic(frac=66, last_shift=62):
    """Constants for the hyperbolic CORDIC log in svdd_pl.cpp (log1p_u32).

    Shift sequence 1, 2, 3, 4, 4, 5, ..., 13, 13, ..., 40, 40, ..., last_shift: the
    repeated steps (4, 13, 40) are what makes hyperbolic CORDIC converge.
    Values are round(v * 2^frac), computed with 50-digit decimals.
    """
    from decimal import Decimal, getcontext
    getcontext().prec = 50
    shifts = []
    for i in range(1, last_shift + 1):
        shifts.append(i)
        if i in (4, 13, 40):
            shifts.append(i)
    scale = Decimal(2) ** frac

    def fixed(v):
        return int((v * scale).to_integral_value())

    def atanh(t):
        return ((1 + t) / (1 - t)).ln() / 2

    vals = [fixed(atanh(Decimal(1) / (Decimal(2) ** i))) for i in shifts]
    ln2 = fixed(Decimal(2).ln())
    lines = [
        "#pragma once",
        "// Generated by gen_params.py: hyperbolic CORDIC constants for log1p_u32().",
        f"// Fixed point with {frac} fraction bits, split into high and low 64-bit halves.",
        "namespace svpl {",
        f"static const int CORDIC_FRAC = {frac};",
        f"static const int CORDIC_STEPS = {len(shifts)};",
        "static const unsigned char CORDIC_SHIFT[%d] = {%s};" % (len(shifts), ", ".join(map(str, shifts))),
        "static const unsigned char CORDIC_ATANH_HI[%d] = {%s};" % (len(vals), ", ".join(str(v >> 64) for v in vals)),
        "static const unsigned long long CORDIC_ATANH_LO[%d] = {%s};"
        % (len(vals), ", ".join("0x%016xULL" % (v & (2**64 - 1)) for v in vals)),
        f"static const unsigned char LN2_HI = {ln2 >> 64};",
        f"static const unsigned long long LN2_LO = 0x{ln2 & (2**64 - 1):016x}ULL;",
        "}  // namespace svpl",
        "",
    ]
    out = HERE / "cordic_table.hpp"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
